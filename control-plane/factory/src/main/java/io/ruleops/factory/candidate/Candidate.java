package io.ruleops.factory.candidate;

import io.ruleops.authoring.model.RuleIntent;
import java.nio.charset.StandardCharsets;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * A Candidate is a compiled, verification-ready rule asset that has NOT passed
 * independent verification and release governance (CONTEXT: Candidate). It
 * bundles the compiled IR, the backend artifact and generated verification
 * fixtures. The candidate digest covers the canonical payload files.
 */
public record Candidate(
        String intentId,
        String intentVersion,
        String template,
        String artifactFileName,
        byte[] artifact,
        Map<String, byte[]> fixtures,
        byte[] manifest,
        String digest) {

    /** File name of the manifest inside the candidate bundle. */
    public static final String MANIFEST_FILE = "manifest.json";

    /** Every file of the bundle: artifact, fixtures and the manifest. */
    public Map<String, byte[]> bundleFiles() {
        Map<String, byte[]> files = new LinkedHashMap<>();
        files.put(artifactFileName, artifact);
        files.putAll(fixtures);
        files.put(MANIFEST_FILE, manifest);
        return files;
    }

    /**
     * Inputs assembled from the intent's examples: each snippet becomes a
     * wrapped, parseable Java fixture class (bad examples must produce
     * findings, good examples must not).
     */
    static Map<String, byte[]> fromExamples(RuleIntent intent) {
        Map<String, byte[]> files = new LinkedHashMap<>();
        List<String> bad = intent.spec().examples().bad();
        List<String> good = intent.spec().examples().good();
        boolean structural = "structural-node".equals(intent.spec().semantics().target().kind());
        for (int i = 0; i < bad.size(); i++) {
            files.put("fixtures/bad/Bad" + i + ".java", wrapSnippet("Bad" + i, bad.get(i), structural));
        }
        for (int i = 0; i < good.size(); i++) {
            files.put("fixtures/good/Good" + i + ".java", wrapSnippet("Good" + i, good.get(i), structural));
        }
        return files;
    }

    private static byte[] wrapSnippet(String className, String snippet, boolean structural) {
        String source = "package fixtures;\n\n"
                + "// Generated by the ERF candidate compiler from a governed RuleIntent example.\n"
                + "public final class "
                + className
                + " {\n"
                + (structural ? "    " + snippet.strip() + "\n" : "    void example() {\n        "
                        + snippet.strip() + "\n    }\n")
                + "}\n";
        return source.getBytes(StandardCharsets.UTF_8);
    }
}
