package io.ruleops.factory.candidate;

import io.ruleops.authoring.model.RuleIntent;
import io.ruleops.authoring.model.RuleIr;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Map;

/**
 * A Candidate is a compiled, verification-ready rule asset that has NOT passed
 * independent verification and release governance (CONTEXT: Candidate). It
 * bundles the compiled IR, the backend artifact and generated verification
 * fixtures, all content-addressed through {@link #digest()}.
 */
public record Candidate(
        String intentId,
        String intentVersion,
        RuleIr ir,
        String template,
        String artifactFileName,
        byte[] artifact,
        Map<String, byte[]> fixtures,
        String digest) {

    /** File name of the manifest inside the candidate bundle. */
    public static final String MANIFEST_FILE = "manifest.json";

    public List<String> fileNames() {
        return List.of(artifactFileName, MANIFEST_FILE);
    }
}

/**
 * Inputs assembled from the intent's examples: each snippet becomes a wrapped,
 * parseable Java fixture class (bad examples must produce findings, good
 * examples must not).
 */
final class Fixtures {

    private Fixtures() {}

    static Map<String, byte[]> fromExamples(RuleIntent intent) {
        Map<String, byte[]> files = new java.util.LinkedHashMap<>();
        List<String> bad = intent.spec().examples().bad();
        List<String> good = intent.spec().examples().good();
        for (int i = 0; i < bad.size(); i++) {
            files.put("fixtures/bad/Bad" + i + ".java", wrapSnippet("Bad" + i, bad.get(i)));
        }
        for (int i = 0; i < good.size(); i++) {
            files.put("fixtures/good/Good" + i + ".java", wrapSnippet("Good" + i, good.get(i)));
        }
        return files;
    }

    private static byte[] wrapSnippet(String className, String snippet) {
        String java = "package fixtures;\n\n"
                + "// Generated by the ERF candidate compiler from a governed RuleIntent example.\n"
                + "public final class "
                + className
                + " {\n"
                + "    void example() {\n"
                + "        "
                + snippet.strip()
                + "\n"
                + "    }\n"
                + "}\n";
        return java.getBytes(StandardCharsets.UTF_8);
    }
}
